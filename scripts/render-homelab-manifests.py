#!/usr/bin/env python3
"""Render the homelab sysext's vendored Kubernetes manifests (offline step).

Every component below is pinned to one upstream chart or manifest version and
its sha256. This script downloads them, renders the charts with a pinned Helm
in a pinned container, rewrites every container image reference to
``tag@sha256:<index digest>`` (resolved with a pinned skopeo container) and
writes plain YAML to ``files/homelab/manifests/<NN-component>/``:

  00-crds.yaml        CustomResourceDefinitions (the applier waits for them
                      to be Established)
  01-namespace.yaml   the component's Namespace(s)
  10-<component>.yaml everything else the chart or manifest renders

Hand-written files in the same directories (``20-*.yaml``: the MetalLB pool,
issuers, the default Gateway, ...) are kept; only their image references are
pinned. Generated files start with GENERATED and are replaced on every run.

Site-specific values are ``${HOMELAB_*}`` placeholders that
/usr/libexec/bluefin-homelab-apply fills in from /etc/bluefin/homelab.conf.

The BuildStream build never runs this; it stages the committed YAML. Run it
after changing a pin (needs network and podman):

    python3 scripts/render-homelab-manifests.py
"""

