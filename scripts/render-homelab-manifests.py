def run(cmd: list[str], **kw) -> subprocess.CompletedProcess:
    result = subprocess.run(cmd, text=True, **kw)
    if result.returncode:
        sys.exit(f"{' '.join(cmd)} failed:\n{result.stderr or ''}")
    return result


